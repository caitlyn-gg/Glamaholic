#!/usr/bin/env python3
"""
Regenerates Glamaholic/item-patches.txt, which records the patch each item was added in.
The Fitting Room uses it to filter by expansion, since the game data doesn't include it.

Source: FFXIV Teamcraft's item patch data (MIT licence), https://github.com/ffxiv-teamcraft/ffxiv-teamcraft

Usage: python tools/update_item_patches.py
"""

import json
import os
import urllib.request

BASE_URL = "https://raw.githubusercontent.com/ffxiv-teamcraft/ffxiv-teamcraft/staging/libs/data/src/lib/json/"
OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Glamaholic", "item-patches.txt")


def fetch(name):
    with urllib.request.urlopen(BASE_URL + name, timeout=60) as response:
        return json.load(response)


def main():
    item_patches = fetch("item-patch.json")
    versions = {int(patch_id): patch["version"] for patch_id, patch in fetch("patch-names.json").items()}

    # collapse consecutive item ids from the same patch into ranges
    runs = []
    for item_id in sorted(int(key) for key in item_patches):
        version = versions.get(item_patches[str(item_id)])
        if version is None:
            continue

        if runs and runs[-1][2] == version and runs[-1][1] == item_id - 1:
            runs[-1][1] = item_id
        else:
            runs.append([item_id, item_id, version])

    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as output:
        output.write("# Patch each item was added in, as \"firstId-lastId version\" or \"id version\".\n")
        output.write("# Generated by tools/update_item_patches.py from FFXIV Teamcraft data (MIT licence).\n")
        for first, last, version in runs:
            ids = str(first) if first == last else f"{first}-{last}"
            output.write(f"{ids} {version}\n")

    print(f"Wrote {len(runs)} ranges to {os.path.normpath(OUTPUT)}")


if __name__ == "__main__":
    main()
